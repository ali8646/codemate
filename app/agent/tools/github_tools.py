import os
import re
from typing import Optional
from github import Github, GithubException
from app.core.config import settings
from app.schemas.audit import AuditFinding


def parse_repo_owner_and_name(repo_target: str) -> Optional[tuple]:
    """
    Extracts (owner, repo_name) from a GitHub URL or string like 'owner/repo'.
    """
    # Matches:
    # https://github.com/owner/repo
    # git@github.com:owner/repo.git
    # owner/repo
    pattern = r"(?:github\.com[/:])?([A-Za-z0-9_.-]+)/([A-Za-z0-9_.-]+?)(?:\.git|/)?$"
    match = re.search(pattern, repo_target.strip())
    if match:
        owner = match.group(1)
        repo_name = match.group(2)
        return owner, repo_name
    return None


def format_github_issue_body(finding: AuditFinding, repo_full_name: str) -> str:
    """
    Constructs a clear, professional GitHub issue body for an audit finding.
    """
    severity_emoji = {
        "CRITICAL": "🚨",
        "HIGH": "⚠️",
        "MEDIUM": "🔍",
        "LOW": "ℹ️",
        "INFO": "💡",
    }.get(finding.severity.value, "⚠️")

    lines_str = (
        f"L{finding.line_start}-L{finding.line_end}"
        if finding.line_start and finding.line_end
        else (f"L{finding.line_start}" if finding.line_start else "")
    )
    file_link = f"`{finding.file_path}`"
    if lines_str:
        file_link += f" ({lines_str})"

    diff_section = ""
    if finding.code_diff:
        diff_section = f"""
### 💡 Proposed Remediation Diff

```diff
{finding.code_diff.strip()}
```
"""

    reproduction_section = ""
    if finding.reproduction:
        reproduction_section = f"""
### 🔬 Reproduction & Technical Context
{finding.reproduction.strip()}
"""

    body = f"""## {severity_emoji} [{finding.severity.value}] {finding.title}

* **Category**: `{finding.category.value}`
* **Severity**: `{finding.severity.value}`
* **Affected File**: {file_link}

### 📋 Description
{finding.explanation.strip()}
{reproduction_section}{diff_section}
---
*Automated audit and remediation advisory generated by [CodeMate](https://github.com/ali8646/codemate) 🛡️⚡*
"""
    return body.strip()


def file_github_issue(
    repo_target: str,
    finding: AuditFinding,
    github_token: Optional[str] = None,
) -> Optional[str]:
    """
    Creates an issue on GitHub for the given audit finding using the GitHub API.
    Returns the HTML URL of the created issue, or None if creation failed/disabled.
    """
    token = github_token or settings.GITHUB_TOKEN or os.getenv("GITHUB_TOKEN")
    if not token:
        print("[CodeMate] Skipping GitHub issue creation: No GITHUB_TOKEN configured.")
        return None

    parsed = parse_repo_owner_and_name(repo_target)
    if not parsed:
        print(f"[CodeMate] Cannot parse repository owner/name from '{repo_target}'.")
        return None

    owner, repo_name = parsed
    repo_slug = f"{owner}/{repo_name}"

    try:
        gh = Github(token)
        repo = gh.get_repo(repo_slug)

        title = f"[{finding.severity.value}] {finding.title}"
        body = format_github_issue_body(finding, repo_slug)
        
        labels = ["codemate-audit"]
        if finding.category.value.lower() == "security":
            labels.append("security")
        elif finding.category.value.lower() == "performance":
            labels.append("performance")

        issue = repo.create_issue(
            title=title,
            body=body,
            labels=labels,
        )
        return issue.html_url
    except GithubException as e:
        print(f"[CodeMate] GitHub API error when creating issue on {repo_slug}: {e}")
        return None
    except Exception as e:
        print(f"[CodeMate] Unexpected error creating GitHub issue: {e}")
        return None
